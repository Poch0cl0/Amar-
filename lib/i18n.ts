export type TranslationTree = (typeof translations)[Lang]

export function getTranslations(lang: Lang): TranslationTree {
  return translations[lang]
}

export function t(lang: Lang, path: string, vars?: Record<string, string | number>): string {
  const parts = path.split('.')
  let current: unknown = translations[lang]

  for (const part of parts) {
    if (typeof current !== 'object' || current === null || !(part in current)) {
      return path
    }
    current = (current as Record<string, unknown>)[part]
  }

  if (typeof current !== 'string') return path

  if (!vars) return current

  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replace(`{${key}}`, String(value)),
    current,
  )
}

export function readStoredLang(): Lang | null {
  if (typeof window === 'undefined') return null
  const stored = localStorage.getItem(STORAGE_KEY)
  return stored === 'en' || stored === 'es' ? stored : null
}

export function writeStoredLang(lang: Lang): void {
  if (typeof window === 'undefined') return
  localStorage.setItem(STORAGE_KEY, lang)
}

